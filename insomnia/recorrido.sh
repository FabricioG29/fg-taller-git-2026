#!/usr/bin/env bash
# Recorrido de la colección Insomnia con curl (misma secuencia). Base vacía: borrar data/ antes de arrancar.
B=${1:-http://localhost:8080}
J="Content-Type: application/json"
p(){ echo; echo "### $1"; echo "$2 $3"; if [ -n "$4" ]; then curl -s -w "\n-> HTTP %{http_code}\n" -X "$2" -H "$J" -d "$4" "$B$3"; else curl -s -w "\n-> HTTP %{http_code}\n" -X "$2" "$B$3"; fi; }
p "01 GET / (servicio vivo)" GET '/'
p "02 POST crear pistola Glock-18" POST '/api/armas' '{"tipo": "pistola", "nombre": "Glock-18", "precio": 200, "equipo": "TERRORISTAS", "danio": 30}'
p "03 POST crear granada HE" POST '/api/armas' '{"tipo": "granada", "nombre": "HE Grenade", "precio": 300, "equipo": "AMBOS", "danio": 98, "radioExplosion": 5.0, "tiempoActivacion": 1.5, "efecto": "Explosión de fragmentación"}'
p "04 POST crear rifle AK-47" POST '/api/armas' '{"tipo": "rifle", "nombre": "AK-47", "precio": 2700, "equipo": "TERRORISTAS", "danio": 36, "precision": 0.8, "cargador": 30, "reserva": 90, "cadencia": 10}'
p "05 GET listar armas" GET '/api/armas'
p "06 GET arma por id" GET '/api/armas/1'
p "07 PATCH arma (nombre y precio)" PATCH '/api/armas/1' '{"nombre": "Glock-18 Custom", "precio": 250}'
p "08 GET armas del bando TERRORISTAS" GET '/api/armas?equipo=TERRORISTAS'
p "09 DELETE arma AK-47" DELETE '/api/armas/3'
p "10 GET arma borrada (id inexistente)" GET '/api/armas/3'
p "11 POST jugador Fabri (TERRORISTAS)" POST '/api/jugadores' '{"nombre": "Fabri", "equipo": "TERRORISTAS"}'
p "12 POST jugador Rival (ANTITERRORISTAS)" POST '/api/jugadores' '{"nombre": "Rival", "equipo": "ANTITERRORISTAS"}'
p "13 GET listar jugadores" GET '/api/jugadores'
p "14 GET inspección (armas, jugadores y disparos)" GET '/api/inspeccion'
p "15 POST simular 3 disparos Fabri → Rival con la Glock" POST '/api/simulaciones/disparos' '{"atacanteId": 1, "objetivoId": 2, "armaId": 1, "veces": 3}'
p "16 GET Rival después de simular" GET '/api/jugadores/2'
p "17 GET Glock después de simular" GET '/api/armas/1'
p "18 GET disparos recibidos por Rival" GET '/api/disparos?objetivoId=2'
p "19 POST recargar la Glock" POST '/api/armas/1/recarga'
p "20 POST arma ilegal (daño negativo) → ValorInvalidoException" POST '/api/armas' '{"tipo": "pistola", "nombre": "Rota", "precio": 200, "equipo": "TERRORISTAS", "danio": -5}'
p "21 GET listar armas (no creció)" GET '/api/armas'
p "22 GET arma inexistente → RecursoNoEncontradoException" GET '/api/armas/999'
p "23 POST preparar P250 con 1 sola bala" POST '/api/armas' '{"tipo": "pistola", "nombre": "P250", "precio": 300, "equipo": "AMBOS", "danio": 30, "precision": 0.9, "cargador": 1, "reserva": 0}'
p "24 POST simular 2 disparos con 1 bala → SinMunicionException" POST '/api/simulaciones/disparos' '{"atacanteId": 1, "objetivoId": 2, "armaId": 4, "veces": 2}'
p "25 GET P250 (rollback: sigue 1/0)" GET '/api/armas/4'
p "26 POST preparar jugador Bot (vida 1, sin chaleco)" POST '/api/jugadores' '{"nombre": "Bot", "equipo": "ANTITERRORISTAS", "vida": 1, "armadura": 0}'
p "27 POST simular disparo que elimina al Bot" POST '/api/simulaciones/disparos' '{"atacanteId": 1, "objetivoId": 3, "armaId": 1, "veces": 1}'
p "28 POST disparar a un eliminado → JugadorEliminadoException" POST '/api/simulaciones/disparos' '{"atacanteId": 1, "objetivoId": 3, "armaId": 1, "veces": 1}'
p "29 POST tipo de arma desconocido → JSON inválido" POST '/api/armas' '{"tipo": "cuchillo", "nombre": "Karambit", "precio": 0, "equipo": "AMBOS", "danio": 40}'
